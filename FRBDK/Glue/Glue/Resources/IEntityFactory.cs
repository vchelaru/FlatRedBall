using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace REPLACED_NAMESPACE
{
    public interface IEntityFactory
    {
        object CreateNew(float x = 0, float y = 0);
        object CreateNew(Microsoft.Xna.Framework.Vector3 position);
        object CreateNew(FlatRedBall.Graphics.Layer layer);
        int NewInstancesCreatedThisScreen { get; }
        void Initialize(string contentManager);
        void ClearListsToAddTo();

        void Destroy();


        System.Collections.Generic.List<System.Collections.IList> ListsToAddTo { get; }
    }


    public static class FactoryManager
    {
        static Dictionary<string, IEntityFactory> FactoryDictionary = new Dictionary<string, IEntityFactory>();

        static List<IEntityFactory> Factories = new List<IEntityFactory>();

#if EntityFactoryRegistry
        static Dictionary<string, IEntityFactory> RegisteredFactories = new Dictionary<string, IEntityFactory>();

        /// <summary>
        /// Registers the factory for an entity so it is found by name without reflection. Native AOT and trimming
        /// remove the constructors and properties that the reflection lookup needs, so the generated game class calls
        /// this once per factory at startup. Names that are not registered still fall back to reflection.
        /// </summary>
        /// <param name="entityName">The entity name, qualified or not. Only the part after the last '\', '/' or '.' is used.</param>
        /// <param name="factory">The factory that creates the entity.</param>
        public static void Register(string entityName, IEntityFactory factory)
        {
            RegisteredFactories[GetUnqualifiedName(entityName)] = factory;

            // Anything cached before this call may be missing the new factory.
            FactoryDictionary.Clear();
            Factories = new List<IEntityFactory>();
        }

        static string GetUnqualifiedName(string entityName)
        {
            var index = entityName.LastIndexOfAny(new[] { '\\', '/', '.' });
            return index < 0 ? entityName : entityName.Substring(index + 1);
        }
#endif

        public static IEnumerable<IEntityFactory> GetAllFactories()
        {
            if (Factories.Count == 0)
            {
                FillWithFactories();
            }
            return Factories.ToList();
        }

        /// <summary>
        /// Gets a Factory for the unqualified entity name. For example, to get a factory for an Entity named 
        /// "Enemy", pass the argument "Enemy" without the prefix "Entities/"
        /// </summary>
        /// <param name="entityName">The unqualified Entity name.</param>
        /// <returns>An IFactory instance for the argument entity name.</returns>
        public static IEntityFactory Get(string entityName)
        {
            if (FactoryDictionary.ContainsKey(entityName))
            {
                return FactoryDictionary[entityName];
            }
            else
            {
                var factory = FindFactory(entityName);
                FactoryDictionary[entityName] = factory;
                return factory;
            }
        }

        public static IEntityFactory Get(Type type) => Get(type.Name);

        static Type[] typesInThisAssembly;
#if EntityFactoryRegistry
        [System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage("Trimming", "IL2070", Justification = "Only reached for entity names that were not registered, such as factories written by hand or generated by an older Glue. Generated factories are registered at startup.")]
        [System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage("Trimming", "IL2075", Justification = "Only reached for entity names that were not registered, such as factories written by hand or generated by an older Glue. Generated factories are registered at startup.")]
#endif
        public static IEntityFactory FindFactory(string entityType)
        {
#if EntityFactoryRegistry
            if (RegisteredFactories.TryGetValue(GetUnqualifiedName(entityType), out var registeredFactory))
            {
                return registeredFactory;
            }
#endif
            if (Factories.Count == 0)
            {
                FillWithFactories();
            }
            var factory = Factories.FirstOrDefault(item =>
            {
                var type = item.GetType();
                var methodInfo = type.GetMethod("CreateNew", new[] { typeof(FlatRedBall.Graphics.Layer), typeof(float), typeof(float), typeof(float) });
                if (methodInfo == null)
                {
                    // The method was removed by trimming, so reflection cannot match this factory.
                    return false;
                }
                var returnTypeString = methodInfo.ReturnType.Name;

                return entityType == returnTypeString ||
                    entityType.EndsWith("\\" + returnTypeString) ||
                    entityType.EndsWith("/" + returnTypeString) ||
                    entityType.EndsWith("." + returnTypeString);
            });
            return factory;

        }

#if EntityFactoryRegistry
        [System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage("Trimming", "IL2026", Justification = "Only reached for entity names that were not registered, such as factories written by hand or generated by an older Glue. Generated factories are registered at startup.")]
        [System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage("Trimming", "IL2070", Justification = "Only reached for entity names that were not registered, such as factories written by hand or generated by an older Glue. Generated factories are registered at startup.")]
#endif
        private static void FillWithFactories()
        {
            if (typesInThisAssembly == null)
            {
                var assembly = System.Reflection.Assembly.GetExecutingAssembly();
                typesInThisAssembly = assembly.GetTypes();
            }


            var filteredTypes =
                typesInThisAssembly.Where(t => t.GetInterfaces().Contains(typeof(IEntityFactory))
                            && t.GetConstructor(Type.EmptyTypes) != null);

            Factories = filteredTypes
                .Select(
                    t =>
                    {
                        var propertyInfo = t.GetProperty("Self");
                        var value = propertyInfo?.GetValue(null, null);
                        return value as IEntityFactory;
                    })
                .Where(item => item != null)
                .ToList();

#if EntityFactoryRegistry
            foreach (var registeredFactory in RegisteredFactories.Values)
            {
                if (!Factories.Contains(registeredFactory))
                {
                    Factories.Add(registeredFactory);
                }
            }
#endif
        }

        static StringBuilder creationReportBuilder = new StringBuilder();
        public static string GetCreationReport(bool includeFactoriesWith0Instances = false)
        {
            creationReportBuilder.Clear();
            var allFactories = GetAllFactories()
                .OrderByDescending(item => item.NewInstancesCreatedThisScreen);
            foreach (var factory in allFactories)
            {
                if (includeFactoriesWith0Instances || factory.NewInstancesCreatedThisScreen > 0)
                {
                    creationReportBuilder.AppendLine($"{factory.GetType().Name}:{factory.NewInstancesCreatedThisScreen:N0}");
                }
            }

            return creationReportBuilder.ToString();
        }
    }
}
